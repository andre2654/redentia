export function lotesPrecoTeto(abertos?: number): string[][] {
  const n = PRECO_TETO_ORDEM.length
  const todos: string[][] = []
  for (let i = 0; i < n; i += PRECO_TETO_TAMANHO_LOTE) {
    todos.push(PRECO_TETO_ORDEM.slice(i, i + PRECO_TETO_TAMANHO_LOTE))
  }
  const limite = abertos ?? PRECO_TETO_LOTES_ABERTOS
  return todos.slice(0, Math.max(0, limite))
}

export function tickersDosLotesAbertos(abertos?: number): string[] {
  return lotesPrecoTeto(abertos).flat()
}

